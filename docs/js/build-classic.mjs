// Generates docs/js/hms-mvar.classic.js from docs/js/hms-mvar.js. The classic file is the SAME code
// without the two `export` statements, wrapped in a function, so it loads with a plain
// <script src> (including from a file:// page) and in Node with require(). It sets the global
// HmsMvar (window.HmsMvar in a browser) and module.exports where a `module` exists. Nothing else
// differs; test/classic.test.mjs checks the committed file is byte-for-byte what this script makes
// and that both builds decode real files identically.
//
//   node docs/js/build-classic.mjs            write hms-mvar.classic.js next to hms-mvar.js
//   node docs/js/build-classic.mjs --check    exit 1 if the committed file is out of date
//
// Deterministic: no dates, no paths, no environment in the output; no dependencies.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export function buildClassic(src) {
  const norm = src.replace(/\r\n/g, '\n');
  const headEnd = norm.indexOf('*/\n');
  if (!norm.startsWith('/*!') || headEnd < 0) throw new Error('hms-mvar.js: licence header not found');
  const head = norm.slice(0, headEnd + 3);
  let body = norm.slice(headEnd + 3);
  const exportBlock = /\nexport \{[^}]*\};\nexport default HmsMvar;\n$/;
  if (!exportBlock.test(body)) throw new Error('hms-mvar.js: expected the two trailing export statements');
  body = body.replace(exportBlock, '\n');
  if (/^\s*(export|import)\s/m.test(body)) throw new Error('hms-mvar.js: stray import/export left in the body');
  return head + '\n/* GENERATED by build-classic.mjs from hms-mvar.js. Do not edit; edit the module and rebuild. */\n'
    + '(function () {\n\'use strict\';\n' + body.replace(/^\n+/, '\n')
    + 'if (typeof module === \'object\' && module && module.exports) module.exports = HmsMvar;\n})();\n';
}

const here = path.dirname(fileURLToPath(import.meta.url));
export const MODULE_PATH = path.join(here, 'hms-mvar.js');
export const CLASSIC_PATH = path.join(here, 'hms-mvar.classic.js');

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = buildClassic(fs.readFileSync(MODULE_PATH, 'utf8'));
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(CLASSIC_PATH) ? fs.readFileSync(CLASSIC_PATH, 'utf8') : null;
    if (cur !== out) { console.error('hms-mvar.classic.js is out of date: run node docs/js/build-classic.mjs'); process.exit(1); }
    console.log('hms-mvar.classic.js is up to date');
  } else {
    fs.writeFileSync(CLASSIC_PATH, out);
    console.log('wrote ' + path.basename(CLASSIC_PATH) + ' (' + out.length + ' bytes)');
  }
}
